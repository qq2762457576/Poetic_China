  /* 解析: 作者(非'*') + 标题包含关键词 + 正文包含片段 */
  function resolve(list) {
    var data = window.POEM_DATA || [];
    var out = [];
    var seen = {};
    list.forEach(function (e) {
      var key = e[0], author = e[1], frag = e[2];
      for (var i = 0; i < data.length; i++) {
        var r = data[i];
        if (author !== '*' && r[1] !== author) continue;
        if (r[0].indexOf(key) === -1) continue;
        if (frag && r[6].indexOf(frag) === -1) continue;
        var sig = r[0] + '|' + r[1];
        if (seen[sig]) break;
        seen[sig] = 1;
        out.push({ title: r[0], author: r[1], dynasty: r[2], text: r[6] });
        break;
      }
      if (!seen[key + '|' + author] && out.length === 0) { /* noop */ }
    });
    return out;
  }

